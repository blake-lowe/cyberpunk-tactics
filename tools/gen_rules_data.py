#!/usr/bin/env python3
"""Regenerates data/rules/{skills,cyberware}.json from the docs/rules/*.md references.

Run from the repo root:  python3 tools/gen_rules_data.py
Mechanical effects ("fx") for cyberware are hand-maintained in CYBER_FX below; everything
else comes from the reference tables so docs and data can't drift apart.
"""
import json
import re

STATS = {"INT", "REF", "DEX", "TECH", "COOL", "WILL", "LUCK", "MOVE", "BODY", "EMP"}


def slug(s):
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def rows(text):
    for line in text.splitlines():
        if line.startswith("|") and not line.startswith("|---"):
            yield [c.strip() for c in line.strip().strip("|").split("|")]


def gen_skills():
    md = open("docs/rules/characters.md").read()
    sec = md.split("### Master skill list")[1].split("\n## ")[0]
    skills = {}
    for c in rows(sec):
        if len(c) != 5 or c[1] not in STATS:
            continue
        skills[slug(c[0])] = {"name": c[0], "stat": c[1], "category": c[2], "x2": c[3] == "x2", "basic": "(Basic" in c[4]}
    # Surgery is the Medtech Medicine specialty (p149), rolled as TECH + Surgery.
    skills["surgery"] = {"name": "Surgery", "stat": "TECH", "category": "Role", "x2": False, "basic": False}
    out = {"_source": "Generated by tools/gen_rules_data.py from docs/rules/characters.md (CPR core p82-85, p130-142).", "skills": skills}
    json.dump(out, open("data/rules/skills.json", "w"), indent=1)
    return len(skills)


