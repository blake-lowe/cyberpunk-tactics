#!/usr/bin/env python3
"""Builds data/world/*.json from the world reference docs (docs/world/*.md).

The docs hold the distilled Night City material: short paraphrases with page citations, and
next to each, a fenced data block the game reads:

    ```world factions.factions.maelstrom
    {"name": "Maelstrom", "kind": "gang", ..., "cite": "NC2047 p.NN"}
    ```

The info string is `world <file>[.<key>.<key>...]`: the block's JSON value is placed at that path
in data/world/<file>.json (intermediate objects are created; a path may only be set once).
Blocks are read in file-name order, then document order, which is the order keys come out in.

Run from the repo root:
    python3 tools/gen_world_data.py           # regenerate
    python3 tools/gen_world_data.py --check   # exit 1 if data/world/ is out of date (tools/test.sh)

Never paste rulebook text into the docs: numbers and short paraphrases with a cite only.
"""
import glob
import json
import os
import re
import sys

DOCS = "docs/world"
OUT = "data/world"
BLOCK = re.compile(r"^```world[ \t]+([A-Za-z0-9_.\-]+)[ \t]*\n(.*?)^```[ \t]*$", re.M | re.S)
SOURCE = "Generated by tools/gen_world_data.py from docs/world/*.md: edit the docs, not this file."


def build():
    files = {}   # file -> dict
    where = {}   # (file, path) -> "doc:line" of the block that set it
    problems = []
    for doc in sorted(glob.glob(os.path.join(DOCS, "*.md"))):
        text = open(doc, encoding="utf-8").read()
        for m in BLOCK.finditer(text):
            target, body = m.group(1), m.group(2)
            line = text.count("\n", 0, m.start()) + 1
            at = "%s:%d" % (doc, line)
            try:
                value = json.loads(body)
            except json.JSONDecodeError as ex:
                problems.append("%s: bad JSON in `world %s` block: %s" % (at, target, ex))
                continue
            parts = target.split(".")
            fname, path = parts[0], parts[1:]
            root = files.setdefault(fname, {"_source": SOURCE})
            key = (fname, tuple(path))
            if key in where:
                problems.append("%s: `%s` already set at %s" % (at, target, where[key]))
                continue
            where[key] = at
            if not path:
                if not isinstance(value, dict):
                    problems.append("%s: a whole-file block must be an object" % at)
                    continue
                root.update(value)
                continue
            node = root
            for p in path[:-1]:
                node = node.setdefault(p, {})
                if not isinstance(node, dict):
                    problems.append("%s: `%s` passes through a non-object" % (at, target))
                    break
            else:
                node[path[-1]] = value
    return files, problems


def render(d):
    return json.dumps(d, indent="\t", ensure_ascii=False) + "\n"


def main():
    check = "--check" in sys.argv
    files, problems = build()
    for p in problems:
        print("ERROR:", p, file=sys.stderr)
    if problems:
        return 1
    stale = []
    for fname, data in files.items():
        path = os.path.join(OUT, fname + ".json")
        new = render(data)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != new:
            stale.append(path)
            if not check:
                os.makedirs(OUT, exist_ok=True)
                open(path, "w", encoding="utf-8").write(new)
    if check:
        for p in stale:
            print("STALE:", p, "(run python3 tools/gen_world_data.py)", file=sys.stderr)
        return 1 if stale else 0
    print("world data: %d file(s), %d updated" % (len(files), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
