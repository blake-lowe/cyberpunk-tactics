ROLE_COLS = ["rockerboy", "solo", "netrunner", "tech", "medtech", "media", "lawman", "exec", "fixer", "nomad"]
ROLE_NAMES = {"Rockerboy": "rockerboy", "Solo": "solo", "Netrunner": "netrunner", "Tech": "tech", "Medtech": "medtech",
              "Media": "media", "Lawman": "lawman", "Exec": "exec", "Fixer": "fixer", "Nomad": "nomad"}
STAT_ORDER = ["INT", "REF", "DEX", "TECH", "COOL", "WILL", "LUCK", "MOVE", "BODY", "EMP"]


def skill_id(name):
    name = re.sub(r"\s*\((choose 1|Your Home|Streetslang|x2)\)", "", name)
    return slug(name)


def gen_roles(skills, cyber):
    md = open("docs/rules/characters.md").read()
    roles = {r: {"stat_rows": [], "skills": {}, "cyberware": []} for r in ROLE_COLS}
    # STAT templates (p74-77)
    for c in rows(md.split("### Streetrat STAT templates")[1].split("\n## ")[0]):
        if c[0] in ROLE_NAMES and c[1].isdigit():
            roles[ROLE_NAMES[c[0]]]["stat_rows"].append(dict(zip(STAT_ORDER, map(int, c[2:12]))))
    # Streetrat skills (p86-87)
    sec = md.split("### Streetrat starting skill levels")[1].split("### ")[0]
    for c in rows(sec):
        if len(c) == 11 and c[1].isdigit():
            for i, r in enumerate(ROLE_COLS):
                roles[r]["skills"][skill_id(c[0])] = int(c[i + 1])
    for line in sec.splitlines():
        m = re.match(r"- (\w+): (.+)", line)
        if m and m.group(1) in ROLE_NAMES:
            for part in m.group(2).split(", "):
                lm = re.match(r"(.+?)\s+(\d+)$", part)
                name, lvl = (lm.group(1), int(lm.group(2))) if lm else (part, 6)
                roles[ROLE_NAMES[m.group(1)]]["skills"][skill_id(name)] = lvl
    # Starting cyberware (p117): "A or B" becomes a choice list.
    stated = {}
    for c in rows(md.split("### Streetrat starting cyberware")[1].split("### ")[0]):
        if c[0] in ROLE_NAMES:
            for item in c[1].split(", "):
                roles[ROLE_NAMES[c[0]]]["cyberware"].append([slug(x) for x in item.split(" or ")])
            stated[ROLE_NAMES[c[0]]] = int(c[2].split()[0])
    problems = []
    for r, d in roles.items():
        if len(d["stat_rows"]) != 10:
            problems.append(f"{r}: {len(d['stat_rows'])} stat rows")
        for s in d["skills"]:
            if s not in skills:
                problems.append(f"{r}: unknown skill {s}")
        hl = 0
        for choice in d["cyberware"]:
            for cid in choice:
                if cid not in cyber:
                    problems.append(f"{r}: unknown cyberware {cid}")
            hl += cyber.get(choice[0], {}).get("hl_flat", 0)
        if hl != stated.get(r):
            problems.append(f"{r}: HL {hl} != stated {stated.get(r)}")
    out = {"_source": "Generated by tools/gen_rules_data.py from docs/rules/characters.md (CPR core p74-77, p86-87, p117).", "roles": roles}
    json.dump(out, open("data/rules/roles.json", "w"), indent=1)
    return problems


