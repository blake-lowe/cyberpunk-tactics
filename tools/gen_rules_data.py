INSTALL = {"M": "mall", "C": "clinic", "H": "hospital", "-": "chip"}


def parse_hl(s):
    """'2d6 (7)' -> ('2d6', 7); '0' -> ('', 0); '1d6/2 (2)' -> ('1d6/2', 2)."""
    m = re.match(r"([0-9d/]+)\s*\((\d+)\)", s)
    if m:
        return m.group(1), int(m.group(2))
    return "", 0


def parse_cost(s):
    m = re.search(r"([\d,]+)\s*eb", s)
    return int(m.group(1).replace(",", "")) if m else 0


def gen_cyberware():
    md = open("docs/rules/cyber-net.md").read()
    sec = md.split("### 2.3 Cyberware table")[1].split("\n## ")[0]
    items = {}
    category = None
    for block in re.split(r"\n(?=\*\*)", sec):
        m = re.match(r"\*\*([A-Za-z ]+?)\s*\(", block)
        if m:
            category = slug(m.group(1))
        for c in rows(block):
            if c[0] in ("Name", "Dice") or len(c) < 4:
                continue
            if len(c) == 4:  # Fashionware: Name | Inst | Effect | Cost
                name, inst, effect, cost = c
                hl = "0"
            else:
                name, inst, effect, hl, cost = c[:5]
            sid = slug(name)
            dice, flat = parse_hl(hl)
            items[sid] = {"name": name, "category": category, "install": INSTALL.get(inst, inst), "effect": effect,
                          "hl_dice": dice, "hl_flat": flat, "cost": parse_cost(cost),
                          "borgware": category == "borgware"}
            if sid in CYBER_FX:
                items[sid]["fx"] = CYBER_FX[sid]
    missing = sorted(set(CYBER_FX) - set(items))
    out = {"_source": "Generated by tools/gen_rules_data.py from docs/rules/cyber-net.md (CPR core p111-116).", "cyberware": items}
    json.dump(out, open("data/rules/cyberware.json", "w"), indent=1)
    return len(items), missing


